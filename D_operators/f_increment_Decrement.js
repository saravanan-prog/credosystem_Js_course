
/**
 * (i++) post increment / decrement  => first print, next calc
 * (++i) pre increment  / decrement  => first calc , next print 

 **/

let i = 3;

console.log("i====>",i++)    //  -> 3
console.log("i=====>",i)     //  -> 4
console.log("i======>",++i)  //  -> 5
console.log("i======>",i)    //  -> 5
console.log("i======>",i--)  //  -> 5
console.log("i======>",--i)  //  -> 3
console.log("i=====>",i)     //  -> 3





