function comparissionOperators(){
    
    const firstValue = 75;
    const secondValue = "125";

    console.log("Checking Greater then ===>",(firstValue > secondValue) )          //t

    console.log("Checking Less then ===>",(firstValue < secondValue) )        // f

    console.log("Checking Greater then Equal to ===>",(firstValue >= secondValue) )    // t   

    console.log("Checking Less then Equal to ===>",(firstValue <= secondValue) )   // t

    console.log("Equal to  ===>",(firstValue == secondValue) )                     //f

    console.log("Strict equal to  ===>",(firstValue === secondValue) )             // f

}

comparissionOperators()
 