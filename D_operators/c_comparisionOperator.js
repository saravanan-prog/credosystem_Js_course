const firstValue = 100;
const secondValue = 125;

console.log("Checking Greater then ===>",(firstValue > secondValue) )          // false

console.log("Checking Less then ===>",(firstValue < secondValue) )             // true

console.log("Checking Less then Equal to ===>",(firstValue <= secondValue) )   // true

console.log("Equal to  ===>",(firstValue == secondValue) )                     //false

console.log("Strict equal to  ===>",(firstValue === secondValue) )             // false 


 