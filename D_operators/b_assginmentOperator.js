function assignmentOperators() {
  var x = 10;
  console.log("x value is ====>", x);
  
  x += 25;    /* addition assignment */
  console.log("addition assignment====>", x);    //35

  
  x -= 10;   /* subraction assignment */
  console.log("subraction assignment====>", x);  //0

  
  x *= 2;    /* Multiplication assignment */
  console.log("multiplication assignment====>", x);  //20

  
  x /= 2;   /* division assignment */
  console.log("multiplication assignment====>", x);  //5
}
assignmentOperators()