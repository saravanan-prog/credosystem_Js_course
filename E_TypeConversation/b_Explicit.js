function convertStringToNumber(){
    var firstNumber = "100"
    var secondNumber = "500"

    firstNumber  =  Number(firstNumber)
    secondNumber =  Number(secondNumber)

    var result  = firstNumber + secondNumber;    // 600
    console.log("result=====>",result)
}

