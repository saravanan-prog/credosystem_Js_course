/*  Example 1 - Includes functions -> returns to boolean value  */ 

function searchFunctionIncludes(){

    var str = "Hello Javascript welcome to React world"
    var findText = "javascript"
    var availableText     = str.includes(findText)    
    console.log("availableText =====>",availableText)

}
 

/*  Example 2 - indexOf() functions -> returns to index value  */ 


function searchFunctionIndexof(){

    var str = "Hello Javascript welcome to React world"
    var findText = "Javascript"
    var availableText     = str.indexOf(findText)    
    console.log("availableText =====>",availableText)

}




 







    

